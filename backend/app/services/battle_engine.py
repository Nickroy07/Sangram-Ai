# Transcript analysis
# ---------------------------------------------------------------------------

def _sentences(text: str) -> List[str]:
    cleaned = re.sub(r"\s+", " ", text or "").strip()
    if not cleaned:
        return []
    parts = re.split(r"(?<=[.!?])\s+", cleaned)
    return [part.strip() for part in parts if part.strip()]


def _first_sentence(text: str, limit: int = 220) -> str:
    sentences = _sentences(text)
    value = sentences[0] if sentences else (text or "").strip()
    if len(value) > limit:
        value = value[: limit - 1].rstrip() + "…"
    return value


def _contains_concession(text: str) -> bool:
    lowered = (text or "").lower()
    return any(marker in lowered for marker in _CONCESSION_MARKERS)


def derive_turn_metadata(
    round_number: int,
    text: str,
    previous_messages: Sequence[Dict[str, object]],
    current_speaker: str,
) -> Dict[str, Optional[object]]:
    """Extractive turn metadata derived from the real transcript.

    Round/role rules decide which opponent claim is being answered; concession
    language decides ``converging``. No metadata is randomised.
    """
    opponent = "B" if current_speaker == "A" else "A"
    previous_opponent = next(
        (m for m in reversed(previous_messages) if m.get("speaker") == opponent), None
    )
    challenges = (
        _first_sentence(str(previous_opponent["text"]), 180) if previous_opponent else None
    )
    converging = round_number >= 2 and _contains_concession(text)
    contention = None
    if round_number == 1 and current_speaker == "B" and previous_messages:
        contention = "Direct disagreement with the opening position."
    elif round_number == 2 and previous_opponent:
        contention = f"Contesting {previous_opponent['model_name']}'s central claim."
    return {
        "challenges": challenges,
        "contention": contention,
        "converging": converging,
    }


def summarize_round(round_number: int, turns: Sequence[Dict[str, object]]) -> str:
    """Extractive round summary built from the two actual turns."""
    stage = stage_for_round(round_number)
    by_speaker = {str(turn["speaker"]): turn for turn in turns}
    a = by_speaker.get("A")
    b = by_speaker.get("B")
    if a and b:
        return (
            f"{stage.label}: {a['model_name']} argues {_first_sentence(str(a['text']), 170)} "
            f"{b['model_name']} counters with {_first_sentence(str(b['text']), 170)}"
        )
    only = a or b
    if only:
        return f"{stage.label}: {only['model_name']} advances {_first_sentence(str(only['text']), 220)}"
    return f"{stage.label}: no arguments were recorded."


def _content_tokens(text: str) -> set:
    return {
        token
        for token in (match.group(0).lower() for match in _TOKEN_RE.finditer(text or ""))
        if token not in _STOPWORDS
    }


def compute_agreement(
    messages: Sequence[Dict[str, object]],
    fighter_a: str,
    fighter_b: str,
) -> Optional[BattleAgreement]:
    """Computes convergence with the documented lexical claim-overlap method.

    Returns ``None`` if there is not enough transcript to score honestly.
    """
    if not messages:
        return None
    turns_a = [m for m in messages if m.get("speaker") == "A"]
    turns_b = [m for m in messages if m.get("speaker") == "B"]
    if not turns_a or not turns_b:
        return None

    final_a = next(
        (str(m["text"]) for m in reversed(turns_a) if int(m["round"]) == 4), str(turns_a[-1]["text"])
    )
    final_b = next(
        (str(m["text"]) for m in reversed(turns_b) if int(m["round"]) == 4), str(turns_b[-1]["text"])
    )
    tokens_a, tokens_b = _content_tokens(final_a), _content_tokens(final_b)
    union = tokens_a | tokens_b
    overlap = len(tokens_a & tokens_b) / len(union) if union else 0.0

    converging_turns = sum(1 for m in messages if m.get("converging"))
    concession_signal = min(1.0, converging_turns / max(1, len(messages) / 2))

    shared_stance_a = _content_tokens(final_a) & _SHARED_STANCE_MARKERS
    shared_stance_b = _content_tokens(final_b) & _SHARED_STANCE_MARKERS
    shared_signal = 1.0 if (shared_stance_a or shared_stance_b) else 0.0

    score = round(100 * (0.55 * overlap + 0.25 * concession_signal + 0.20 * shared_signal))
    score = max(5, min(95, score))

    note = (
        f"Computed from this transcript, not a demo value. Content-word overlap between the two "
        f"final positions was {overlap:.0%} ({fighter_a} vs {fighter_b}); "
        f"{converging_turns} of {len(messages)} turns contained explicit concession or agreement "
        f"language, and shared agreement vocabulary was {'present' if shared_signal else 'absent'}. "
        "The score measures stance convergence, not factual correctness."
    )
    return BattleAgreement(
        score=score,
        note=note,
        label="Computed agreement estimate",
        demo=False,
        computedAt=datetime.now(timezone.utc),
        method="claim-graph-overlap-v1",
    )


def build_insights(
    messages: Sequence[Dict[str, object]],
    fighter_a: str,
    fighter_b: str,
) -> BattleInsights:
    """Extractive per-fighter stance + concession summaries."""

    def summarize(speaker: str, name: str) -> str:
        turns = [m for m in messages if m.get("speaker") == speaker]
        if not turns:
            return f"{name} produced no recorded turns."
        final = str(turns[-1]["text"])
        stance = _first_sentence(final, 200)
        concessions = [
            _first_sentence(str(m["text"]), 160)
            for m in turns
            if m.get("converging")
        ]
        if concessions:
            return f"{name}: {stance} Conceded/refined: {concessions[-1]}"
        return f"{name}: {stance}"

    return BattleInsights(a=summarize("A", fighter_a), b=summarize("B", fighter_b))


def estimate_tokens(text: str) -> int:
    """Cheap, provider-agnostic token estimate (~4 characters per token)."""
    return max(1, math.ceil(len(text or "") / 4))


def total_transcript_chars(messages: Iterable[Dict[str, object]]) -> int:
    return sum(len(str(m.get("text", ""))) for m in messages)
