_TOKEN_RE = re.compile(r"[a-zA-Z][a-zA-Z'\-]{2,}")


def stage_for_round(round_number: int) -> Stage:
    return STAGES.get(round_number, STAGES[4])


def get_model_profile(model_id: str) -> Optional[ModelProfile]:
    for profile in MODELS_CATALOG:
        if profile.id == model_id:
            return profile
    return None


def get_archetype(archetype_id: Optional[str]) -> Optional[ArchetypeProfile]:
    if not archetype_id:
        return None
    for archetype in ARCHETYPES_CATALOG:
        if archetype.id == archetype_id:
            return archetype
    return None


def default_archetype_for_model(model_id: str) -> Optional[ArchetypeProfile]:
    """Deterministic fallback so every fighter has a cognitive lens."""
    if not MODELS_CATALOG:
        return None
    index = next((i for i, m in enumerate(MODELS_CATALOG) if m.id == model_id), 0)
    return ARCHETYPES_CATALOG[index % len(ARCHETYPES_CATALOG)]


def build_system_prompt(
    model_name: str,
    slot: str,
    archetype: Optional[ArchetypeProfile],
    opponent_name: str,
) -> str:
    """Persona + arena rules for one fighter."""
    persona = ""
    if archetype:
        persona = (
            f"\nYour cognitive archetype is {archetype.name} ({archetype.tag}): "
            f"{archetype.description} Your debating style: {archetype.debateStyle}."
        )
    role = "Fighter A" if slot == "A" else "Fighter B"
    return (
        f"You are {model_name}, competing as {role} in the Sangram AI dialectic arena "
        f"against {opponent_name}.{persona}\n\n"
        "Rules of the arena:\n"
        "- Take a clear, defensible position. Be specific and substantive.\n"
        "- Engage with the opponent's actual arguments, not a caricature.\n"
        "- Concede real weaknesses; do not pretend every point is winnable.\n"
        "- Write continuous prose of roughly 140-220 words. No headings, bullet lists, "
        "preambles, or meta-commentary about being an AI.\n"
        "- Never fabricate statistics or citations. If evidence is uncertain, say so."
    )


def build_transcript(messages: Sequence[Dict[str, object]]) -> str:
    """Renders persisted turns into a compact transcript for the next prompt."""
    if not messages:
        return "(no turns yet)"
    lines: List[str] = []
    current_round = None
    for message in messages:
        round_number = int(message["round"])
        if round_number != current_round:
            current_round = round_number
            stage = stage_for_round(round_number)
            lines.append(f"\n[Round {round_number} — {stage.label}]")
        lines.append(f"{message['model_name']} ({message['speaker']}): {message['text']}")
    return "\n".join(lines).strip()


def build_turn_prompt(
    question: str,
    context: Optional[str],
    messages: Sequence[Dict[str, object]],
    round_number: int,
    model_name: str,
    opponent_name: str,
) -> str:
    stage = stage_for_round(round_number)
    context_block = f"\nCONTEXT / CONSTRAINTS:\n{context.strip()}\n" if context and context.strip() else ""
    return (
        f"DILEMMA UNDER DEBATE:\n{question.strip()}\n"
        f"{context_block}\n"
        f"TRANSCRIPT SO FAR:\n{build_transcript(messages)}\n\n"
        f"You are {model_name}; your opponent is {opponent_name}. "
        f"This is Round {round_number}: {stage.label}. {stage.instruction}"
    )


def build_synthesis_prompt(
    question: str,
    context: Optional[str],
    messages: Sequence[Dict[str, object]],
    fighter_a: str,
    fighter_b: str,
) -> str:
    context_block = f"\nCONTEXT / CONSTRAINTS:\n{context.strip()}\n" if context and context.strip() else ""
    return (
        "You are the neutral synthesis adjudicator for a multi-model dialectic. "
        "You are not either fighter and you do not take sides. Read the full transcript.\n\n"
        f"DILEMMA:\n{question.strip()}\n"
        f"{context_block}\n"
        f"TRANSCRIPT ({fighter_a} = Fighter A, {fighter_b} = Fighter B):\n"
        f"{build_transcript(messages)}\n\n"
        "Write the single consolidated verdict for the user in 180-260 words of continuous prose.\n"
        "Requirements:\n"
        "- State the best-supported answer to the dilemma directly, not a survey of opinions.\n"
        "- Integrate the strongest points from both fighters; name genuine agreements.\n"
        "- Preserve unresolved disagreement honestly instead of papering over it.\n"
        "- End with an actionable recommendation or decision rule.\n"
        "- No headings, bullet lists, or references to 'the debate' as theatre."
    )


def synthesis_system_prompt() -> str:
    return (
        "You are Sangram AI's synthesis engine. Your job is to turn an adversarial multi-model "
        "debate into one honest, decision-ready answer. Be concise, concrete and balanced. "
        "Never invent evidence or attribute claims that were not made."
    )


