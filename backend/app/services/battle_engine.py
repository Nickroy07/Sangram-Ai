"""Dialectic debate engine (Developer 4): prompts, turn metadata and scoring.

This module is deliberately pure (no database or network access) so the debate
logic can be unit-tested independently of providers and persistence.

The arena runs four structured rounds with both fighters speaking in each round:

1. opening   — Opening Arguments
2. counter   — Counterarguments & Challenges
3. rebuttal  — Rebuttals & Concessions
4. final     — Final Positions

A neutral synthesis verdict is then generated by one of the fighters.

Convergence is computed from the actual transcript with a lexical claim-overlap
method (``claim-graph-overlap-v1``): content-word overlap between the fighters'
final positions, explicit concession signals across the debate, and shared
agreement vocabulary. Nothing is drawn from frontend demo numbers.
"""

import math
import re
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Dict, Iterable, List, Optional, Sequence

from app.catalog import ARCHETYPES_CATALOG, MODELS_CATALOG
from app.schemas.battle import BattleAgreement, BattleInsights
from app.schemas.model import ArchetypeProfile, ModelProfile


@dataclass(frozen=True)
class Stage:
    round: int
    key: str
    label: str
    instruction: str


STAGES: Dict[int, Stage] = {
    1: Stage(
        1,
        "opening",
        "Opening Arguments",
        (
            "Open your case. State your position in the first sentence, then give two or three "
            "concrete reasons or pieces of evidence. Do not respond to an opponent yet: this is "
            "your opening statement."
        ),
    ),
    2: Stage(
        2,
        "counter",
        "Counterarguments & Challenges",
        (
            "Attack the strongest specific claim your opponent just made. Name the claim you are "
            "challenging, explain precisely why it fails or is incomplete, and defend your own "
            "position against the most obvious objection."
        ),
    ),
    3: Stage(
        3,
        "rebuttal",
        "Rebuttals & Concessions",
        (
            "Answer your opponent's strongest challenge directly. Concede any point that is genuinely "
            "correct, then explain how your position survives or has been refined. Sharpen the "
            "remaining disagreement instead of repeating your opening."
        ),
    ),
    4: Stage(
        4,
        "final",
        "Final Positions",
        (
            "State your final position and the single strongest reason for it. Identify honestly what "
            "you and your opponent now agree on and what remains genuinely unresolved. Do not introduce "
            "a brand-new line of argument."
        ),
    ),
}

STAGE_BY_KEY = {stage.key: stage for stage in STAGES.values()}

