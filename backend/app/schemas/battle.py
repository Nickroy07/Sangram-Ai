"""Battle, Debate, Message, and SSE Event Schemas.

Defines the exact normalized shape consumed by Sangram AI frontend components,
as documented in docs/BACKEND_CONTRACT.md and src/services/battleService.js.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional
from pydantic import Field

from app.schemas.common import BaseSchema


class BattleStageKey(str, Enum):
    """5 structured debate stages."""
    OPENING = "opening"
    COUNTER = "counter"
    REBUTTAL = "rebuttal"
    FINAL = "final"
    SYNTHESIS = "synthesis"


class SpeakerSlot(str, Enum):
    """Combatant fighter position."""
    A = "A"
    B = "B"


class BattleFighter(BaseSchema):
    """Combatant model profile bound to a battle slot."""

    slot: int = Field(..., ge=0, le=1, description="Fighter position (0 for A, 1 for B)")
    modelId: str = Field(..., description="Model catalog ID (e.g. 'chatgpt', 'claude')")
    name: str = Field(..., description="Display model title")
    provider: str = Field(..., description="AI provider organization")
    modelLabel: str = Field(..., description="Display generation identifier")
    archetypeId: Optional[str] = Field(None, description="Cognitive archetype identifier")
    archetypeName: Optional[str] = Field(None, description="Archetype title")
    archetypeTag: Optional[str] = Field(None, description="Archetype tag")


class BattleMessage(BaseSchema):
    """One dialectic turn in the shared debate timeline."""

    id: str = Field(..., description="Unique message turn identifier")
    round: int = Field(..., ge=1, le=4, description="Debate round (1=Opening, 2=Counter, 3=Rebuttal, 4=Final)")
    stageKey: str = Field(..., description="Stage key: 'opening', 'counter', 'rebuttal', 'final'")
    stageLabel: str = Field(..., description="Display stage title")
    speaker: str = Field(..., description="'A' or 'B'")
    modelId: str = Field(..., description="Catalog identity for accent resolution")
    modelName: str = Field(..., description="Fighter name")
    provider: str = Field(..., description="Provider name")
    modelLabel: str = Field(..., description="Display ID")
    text: str = Field(..., description="Full text argument generated for this turn")
    challenges: Optional[str] = Field(None, description="Named opponent claim being answered")
    contention: Optional[str] = Field(None, description="Explicit disagreement topic")
    converging: bool = Field(False, description="True if position was refined or conceded")
    createdAt: Optional[datetime] = Field(None, description="Message generation timestamp")


class BattleInsights(BaseSchema):
    """Post-debate analytical insights per model."""

    a: str = Field(..., description="Key stance and concession summary for Fighter A")
    b: str = Field(..., description="Key stance and concession summary for Fighter B")


class BattleAgreement(BaseSchema):
    """Consensus convergence score.
    
    Must be nullable/unavailable until genuinely computed by backend claim-graph overlap.
    """

    score: Optional[int] = Field(
        None, ge=0, le=100, description="Genuine computed convergence score (0-100), or None"
    )
    note: Optional[str] = Field(None, description="Explanation of how the score was calculated")
    label: Optional[str] = Field("Agreement estimate", description="Badge label")
    demo: bool = Field(False, description="True only if generated by legacy local mock")
    computedAt: Optional[datetime] = Field(None, description="Timestamp when score was calculated")
    method: Optional[str] = Field(None, description="Algorithmic method (e.g., 'claim-graph-overlap-v1')")


class Battle(BaseSchema):
    """Normalized Battle object consumed by Sangram AI frontend UI components.
    
    Preserves exact field names matching docs/BACKEND_CONTRACT.md.
    """

    id: str = Field(..., description="Unique battle ID")
    status: str = Field("completed", description="pending, running, completed, or failed")
    question: str = Field(..., description="The user dilemma or prompt debated")
    fighters: List[BattleFighter] = Field(..., min_length=2, max_length=2, description="The two combatant fighters")
    messages: List[BattleMessage] = Field(..., description="Chronological shared debate timeline turns")
    roundSummaries: List[str] = Field(..., description="One summary per debate round")
    finalAnswer: str = Field(..., description="Single consolidated synthesis verdict")
    insights: BattleInsights = Field(..., description="Key positions extracted per fighter")
    agreement: Optional[BattleAgreement] = Field(None, description="Computed convergence metric")
    source: str = Field("backend", description="'backend' for live debates, 'local-mock' for legacy")
    createdAt: Optional[datetime] = Field(default_factory=lambda: datetime.now(timezone.utc))


class BattleCreateRequest(BaseSchema):
    """Payload to initiate a new dialectic arena battle."""

    question: str = Field(
        ...,
        min_length=10,
        max_length=1000,
        description="Complex dilemma or prompt to be debated",
        examples=["Should early-stage startups pick Python or Go for high-throughput services?"],
    )
    modelA: str = Field(..., description="Catalog model ID for Fighter A (e.g. 'chatgpt')")
    modelB: str = Field(..., description="Catalog model ID for Fighter B (e.g. 'claude')")
    archetypeA: Optional[str] = Field(None, description="Optional cognitive archetype for Fighter A")
    archetypeB: Optional[str] = Field(None, description="Optional cognitive archetype for Fighter B")
    context: Optional[str] = Field(None, max_length=4000, description="Optional domain background or constraints")
    clientBattleId: Optional[str] = Field(
        None, description="Optional idempotency key provided by client to prevent duplicate runs"
    )


class BattleCreateResponse(BaseSchema):
    """Response returned upon accepting a new battle run (201 Created)."""

    battleId: str = Field(..., description="Created battle identifier")
    streamUrl: str = Field(..., description="SSE event stream endpoint: /api/battles/{id}/events")
    estimatedCost: Optional[int] = Field(
        None, description="Estimated total cost in minor units (cents); null if unknown"
    )


class BattleSummaryCard(BaseSchema):
    """Summary representation for history and dashboard lists."""

    id: str
    title: str
    topic: str = "Arena Dialectic"
    date: str
    models: List[str]
    status: str = "completed"
    roundsCount: int = 4
    summary: str
    consensusScore: Optional[int] = None


# ------------------------------------------------------------------------------
# Server-Sent Events (SSE) Event Payloads
# ------------------------------------------------------------------------------

class SSEBattleStage(BaseSchema):
    """Event: 'battle.stage' — notifies frontend of stage change."""
    round: int
    stageKey: str


class SSEBattleMessageStart(BaseSchema):
    """Event: 'battle.message.start' — initiates typing of a message turn."""
    messageId: str
    speaker: str
    modelId: str
    stageLabel: str


class SSEBattleMessageChunk(BaseSchema):
    """Event: 'battle.message.chunk' — streams progressive text delta."""
    messageId: str
    delta: str


# Alias for backward compatibility
SSEBattleChunk = SSEBattleMessageChunk



class SSEBattleMessageDone(BaseSchema):
    """Event: 'battle.message.done' — signals end of a message turn with extracted claims."""
    messageId: str
    contention: Optional[str] = None
    challenges: Optional[str] = None
    converging: bool = False


class SSEBattleRoundSummary(BaseSchema):
    """Event: 'battle.round.summary' — publishes synthesized round summary."""
    round: int
    summary: str


class SSEBattleSynthesisStart(BaseSchema):
    """Event: 'battle.synthesis.start' — triggers War Room synthesis animation."""
    status: str = "synthesizing"


class SSEBattleFinal(BaseSchema):
    """Event: 'battle.final' — delivers consolidated synthesis, insights, and agreement."""
    finalAnswer: str
    insights: BattleInsights
    agreement: Optional[BattleAgreement] = None


class SSEBattleError(BaseSchema):
    """Event: 'battle.error' — notifies client of a streaming failure."""
    code: str
    message: str
    retryable: bool = False


class SSEBattleDone(BaseSchema):
    """Event: 'battle.done' — terminal SSE event indicating completion."""
    battleId: str
    completedAt: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
